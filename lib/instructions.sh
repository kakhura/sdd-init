# Always-loaded instruction files (CLAUDE.md, AGENTS.md, GEMINI.md, copilot-instructions.md)
# and SPEC-KIT-GUIDE.md.

tpl_instructions() { cat <<'EOF'
# {{PROJECT_NAME}} — agent instructions

{{PROJECT_NAME}} is a {{KIND}} project ({{STACK_LABEL}}; data access: {{DATA_LABEL}}).

## Read first
- `.specify/memory/constitution.md` — non-negotiable project rules.
- `SPEC-KIT-GUIDE.md` — how Spec Kit and the agents work together.

## How work flows
- Non-trivial work goes through Spec Kit: `{{CMD_SPECIFY}}` → `{{CMD_CLARIFY}}` → `{{CMD_PLAN}}` →
  `{{CMD_TASKS}}` → `{{CMD_ANALYZE}}` → `{{CMD_SDD_IMPLEMENT}}` → `{{CMD_CONVERGE}}` → "commit and push".
  Feature folders: `specs/NNN-short-name/`.
- Agents: `planner` (research/plans, no code), `builder` (implements tasks), `reviewer`
  (read-only review), `committer` (git only). During `{{CMD_PLAN}}`, delegate Phase 0 research
  to {{D_PLANNER}}. Use `{{CMD_SDD_IMPLEMENT}}` instead of `{{CMD_IMPLEMENT}}`.
- Small one-file fixes with no schema/contract/security change may go straight to the builder.

## Always
- Flow: {{LAYERING}}
- Before "done":
{{VERIFY_BULLETS}}
- Never read real `.env` files or secrets; never push to {{PROTECTED_BRANCHES_MD}}.
EOF
}

write_instruction_files() {
  local t
  for t in $TOOLS; do
    set_tool_vars "$t"
    case "$t" in
      claude)  tpl_instructions | render | write_managed_block CLAUDE.md ;;
      codex)   tpl_instructions | render | write_managed_block AGENTS.md ;;
      gemini)  tpl_instructions | render | write_managed_block GEMINI.md ;;
      copilot) tpl_instructions | render | write_managed_block .github/copilot-instructions.md ;;
    esac
  done
  set_tool_vars "$PRIMARY_TOOL"
}

build_guide_vars() {
  local t
  GUIDE_TOOL_TABLE='| Step | '
  for t in $TOOLS; do GUIDE_TOOL_TABLE="${GUIDE_TOOL_TABLE}$(tool_label "$t") | "; done
  GUIDE_TOOL_TABLE="${GUIDE_TOOL_TABLE}
|---|"
  for t in $TOOLS; do GUIDE_TOOL_TABLE="${GUIDE_TOOL_TABLE}---|"; done
  local step
  for step in constitution specify clarify checklist plan tasks analyze sdd_implement sdd_review converge; do
    GUIDE_TOOL_TABLE="${GUIDE_TOOL_TABLE}
| ${step//_/-} | "
    for t in $TOOLS; do
      set_tool_vars "$t"
      case $step in
        constitution) GUIDE_TOOL_TABLE="${GUIDE_TOOL_TABLE}\`$CMD_CONSTITUTION\` | " ;;
        specify)      GUIDE_TOOL_TABLE="${GUIDE_TOOL_TABLE}\`$CMD_SPECIFY\` | " ;;
        clarify)      GUIDE_TOOL_TABLE="${GUIDE_TOOL_TABLE}\`$CMD_CLARIFY\` | " ;;
        checklist)    GUIDE_TOOL_TABLE="${GUIDE_TOOL_TABLE}\`$CMD_CHECKLIST\` | " ;;
        plan)         GUIDE_TOOL_TABLE="${GUIDE_TOOL_TABLE}\`$CMD_PLAN\` | " ;;
        tasks)        GUIDE_TOOL_TABLE="${GUIDE_TOOL_TABLE}\`$CMD_TASKS\` | " ;;
        analyze)      GUIDE_TOOL_TABLE="${GUIDE_TOOL_TABLE}\`$CMD_ANALYZE\` | " ;;
        sdd_implement) GUIDE_TOOL_TABLE="${GUIDE_TOOL_TABLE}\`$CMD_SDD_IMPLEMENT\` | " ;;
        sdd_review)   GUIDE_TOOL_TABLE="${GUIDE_TOOL_TABLE}\`$CMD_SDD_REVIEW\` | " ;;
        converge)     GUIDE_TOOL_TABLE="${GUIDE_TOOL_TABLE}\`$CMD_CONVERGE\` | " ;;
      esac
    done
  done
  GUIDE_FILES=''
  for t in $TOOLS; do
    case $t in
      claude)  GUIDE_FILES="${GUIDE_FILES}- **Claude Code**: \`.claude/agents/*.md\`, \`.claude/skills/speckit-*\` (Spec Kit), \`.claude/skills/sdd-*\` (yours), \`CLAUDE.md\`
" ;;
      codex)   GUIDE_FILES="${GUIDE_FILES}- **Codex CLI**: \`.codex/agents/*.toml\`, \`.agents/skills/speckit-*\` (Spec Kit), \`.agents/skills/sdd-*\` (yours), \`AGENTS.md\`
" ;;
      gemini)  GUIDE_FILES="${GUIDE_FILES}- **Gemini CLI**: \`.gemini/agents/*.md\`, \`.gemini/commands/speckit.*.toml\` (Spec Kit), \`.gemini/commands/sdd.*.toml\` (yours), \`GEMINI.md\`
" ;;
      copilot) GUIDE_FILES="${GUIDE_FILES}- **GitHub Copilot**: \`.github/agents/*.agent.md\`, \`.github/skills/speckit-*\` (Spec Kit), \`.github/skills/sdd-*\` (yours), \`.github/copilot-instructions.md\`
" ;;
    esac
  done
  set_tool_vars "$PRIMARY_TOOL"
  register_vars GUIDE_TOOL_TABLE GUIDE_FILES
}

tpl_guide() { cat <<'EOF'
# Spec Kit + Agents Guide — {{PROJECT_NAME}}

> Generated by sdd-init {{SDD_INIT_VERSION}} on {{TODAY}} · Spec Kit {{SPECKIT_VERSION}} · tools: {{TOOLS_LABEL}}

## 1. The mental model

```
 idea ─► spec.md ─► clarify ─► plan.md + research.md ─► tasks.md ─► analyze ─► code ─► converge ─► commit
        (WHAT/WHY)  (Q&A)      (HOW)   ▲                 (steps)    (check)    ▲   ▲    (gaps)      ▲
                                       │                                       │   │                │
                                    planner                               builder reviewer      committer
```

- **Spec Kit** owns the artifacts in `specs/NNN-name/`: `spec.md`, `plan.md`, `research.md`,
  `data-model.md`, `contracts/`, `quickstart.md`, `tasks.md`.
- **The constitution** (`.specify/memory/constitution.md`) owns the rules. Every plan has a
  Constitution Check; every review cites principle numbers.
- **Agents** do the heavy work: `planner` researches, `builder` implements one phase at a
  time, `reviewer` gates each phase, `committer` handles git.
- **`tasks.md`** is the progress board: the builder ticks `[X]`; the main session ticks
  REVIEW GATEs after the reviewer approves.

## 2. What was generated

- `.specify/` — Spec Kit (scripts, core templates, workflows) — managed by Spec Kit.
- `.specify/memory/constitution.md` — your rules (generated; refine it, see step 0 below).
- `.specify/templates/overrides/{spec,plan,tasks}-template.md` — project templates; they win
  over Spec Kit's core templates.
{{GUIDE_FILES}}- `SPEC-KIT-GUIDE.md` — this file. `.specify/sdd-init.env` — your answers (`sdd-init --reuse`).

Spec Kit upgrades (`specify integration upgrade <tool>`) never touch the constitution,
overrides, agents, `sdd-*` skills or instruction files.

## 3. Commands per tool

{{GUIDE_TOOL_TABLE}}

Use the `sdd` implement command instead of Spec Kit's own implement: it runs the builder and
reviewer agents with gates.

## 4. End-to-end flow ({{PRIMARY_TOOL_LABEL}} spelling)

**Step 0 — once: make the constitution match the real code**

```
{{CMD_CONSTITUTION}} Refine this generated constitution against the actual repository: keep principles that are true or agreed, fix commands and paths, add project rules found in README/CI/lint config. Bump to 1.1.0.
```

**Step 1 — branch** (`{{DEFAULT_BRANCH}}` up to date, then a ticket branch, e.g. `{{TICKET_KEY}}-123-short-name`). Or let the committer do it.

**Step 2 — specify (WHAT / WHY)**

```
{{CMD_SPECIFY}} {{TICKET_KEY}}-123: <what users need, who, edge cases, screens/design paths>. Short name: {{TICKET_KEY_LC}}-123-short-name
```

Review `spec.md`: no frameworks, tables or endpoints; access, data and compatibility sections filled.

**Step 3 — clarify**: `{{CMD_CLARIFY}}` — answer up to 5 questions; repeat while `[NEEDS CLARIFICATION]` remains.

**Step 4 — plan (HOW)**

```
{{CMD_PLAN}} Delegate Phase 0 research to the planner agent. <technical direction: tables, endpoints, libraries, constraints>
```

Review `plan.md` carefully: Constitution Check without ❌, the stack sections, verification commands.

**Step 5 — optional checklists**: `{{CMD_CHECKLIST}} security`, `{{CMD_CHECKLIST}} api`, `{{CMD_CHECKLIST}} ux`.

**Step 6 — tasks**: `{{CMD_TASKS}}`

**Step 7 — analyze (read-only)**: `{{CMD_ANALYZE}}` — fix CRITICAL/HIGH findings before building.

**Step 8 — implement**: `{{CMD_SDD_IMPLEMENT}} specs/NNN-short-name` — builder per phase → verify → reviewer gate (max 2 fix rounds).

**Step 9 — converge**: `{{CMD_CONVERGE}}` — appends missing work as tasks; run step 8 again if needed.

**Step 10 — final review and ship**

```
{{CMD_SDD_REVIEW}} specs/NNN-short-name full feature
commit and push
```

## 5. Agents in Spec Kit mode

| Agent | Reads | May write | Must not |
|---|---|---|---|
| planner | constitution, spec, plan, code, docs | `<feature>/research.md` (plan files only when asked) | write code or tasks |
| builder | constitution, plan, tasks, contracts | code, tests, migrations; ticks `[X]` | change spec/plan, tick gates |
| reviewer | constitution, spec, plan, tasks, diff | nothing | edit any file |
| committer | plan (branch), git state | commits, branches, pushes | edit code, force-push, push to {{PROTECTED_BRANCHES_MD}} |

## 6. Verification commands

```bash
{{VERIFY_BLOCK}}```

## 7. Tips

- **Small fix**: skip Spec Kit — "use the builder agent to fix X in Y, then the reviewer".
- **Resume**: `{{CMD_SDD_IMPLEMENT}} specs/NNN-name` skips finished phases.
- **Two features at once**: `.specify/feature.json` points to the current feature; set
  `SPECIFY_FEATURE_DIRECTORY=specs/NNN-x` or pass the folder to the `sdd` commands.
- **Plan wrong mid-build**: re-run `{{CMD_PLAN}}` → `{{CMD_TASKS}}` → `{{CMD_ANALYZE}}`, then continue.
- **Re-generate after changing answers**: `sdd-init --reuse` (backs up changed files into `.sdd-init-backup/`).
- **Upgrade Spec Kit**: `specify self upgrade`, then `specify integration upgrade <tool>` per tool.
EOF
}

write_guide() {
  build_guide_vars
  tpl_guide | render | write_file SPEC-KIT-GUIDE.md
}
